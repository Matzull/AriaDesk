const dictionaries = { en, es };

export function t(key, vars) {
    let text = dictionaries[settings.language]?.[key] ?? en[key] ?? key;
    if (vars) {
        for (const name in vars) text = text.replaceAll(`{${name}}`, vars[name]);
    }
    return text;
}

const optionEntry = (key) => optionNames[settings.language]?.[key] || optionNames.en[key];
export const optionLabel = (key) => optionEntry(key)?.[0] || key;
export const optionHelp = (key) => optionEntry(key)?.[1] || '';

/** Labels for the tray and the macOS application menu. */
export function menuLabels() {
    return Object.fromEntries(Object.keys(en).filter((k) => k.startsWith('menu.')).map((k) => [k.slice(5), t(k)]));
}
